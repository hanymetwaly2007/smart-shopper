import os
import streamlit as st
from google import genai

# إعداد واجهة وتصميم الصفحة
st.set_page_config(page_title="رادار المشتريات والصفقات الأحدث", layout="wide", page_icon="🛒")

st.markdown("<h2 style='text-align: center;'>🛒 رادار الصفقات وأحدث الإصدارات العالمية</h2>", unsafe_allow_html=True)
st.markdown("<p style='text-align: center; color: gray;'>مقارنة شاملة لأحدث 3 موديلات في الرياض مطابقة لكهرباء 220V مع روابط الشراء المباشرة</p>", unsafe_allow_html=True)

# جلب مفتاح API بأمان
api_key = st.secrets.get("GEMINI_API_KEY") or os.environ.get("GEMINI_API_KEY")

query = st.text_input("ما هو المنتج أو الجهاز الذي تبحث عنه؟", placeholder="...مثال: قلاية هوائية، شواية ذكية، صانعة قهوة، مفرمة لحم")

if st.button("فحص أحدث الموديلات وروابط الشراء المباشرة 🚀", use_container_width=True):
    if not query.strip():
        st.warning("يرجى كتابة اسم المنتج أولاً.")
    elif not api_key:
        st.error("مفتاح API غير متوفر في الإعدادات.")
    else:
        with st.spinner("جاري استخراج أحدث الموديلات العالمية وفحص الأسعار وروابط الشراء المباشرة في الرياض..."):
            client = genai.Client(api_key=api_key)
            prompt = f"""أنت خبير استشاري أول في الأجهزة المنزلية والإلكترونيات بالسوق السعودي (مدينة الرياض).
المستخدم يبحث عن: {query}

المطلوب تقديم تقرير استشاري شامل، عميق، واحترافي يغطي:
1. تحديد أفضل وأحدث 3 موديلات عالمية رائدة ومتاحة حالياً بالسوق (ركز على أحدث إصدارات التكنولوجيا مثل الأحواض المزدوجة Dual Zone، التقنيات الذكية المتصلة بالواي فاي، وتقنيات الطهي المتقدمة Combi، وتجنب تماماً ترشيح الموديلات القديمة أو التقليدية).
2. يجب أن تكون جميع الموديلات المرشحة مطابقة 100% للمواصفات القياسية السعودية (SASO): كهرباء 220V-240V وتردد 50/60Hz وقابس ثلاثي بريطاني معتمد.

لكل جهاز من الأجهزة الثلاثة، اذكر بالتفصيل:
- الترتيب والاسم التجاري الكامل مع رقم الموديل الإنجليزي الدقيق (Model Number / SKU).
- المواصفات الفنية المتقدمة (السعة، القوة بالواط، التقنيات الحصرية).
- مطابقة الكهرباء السعودية والتأكيد على رمز الموديل الخليجي المعتمد.
- متوسط السعر الحالي بالريال السعودي في متاجر الرياض (أمازون السعودية، إكسترا، نون، ساكو).
- روابط الشراء المباشرة للسلعة بعينها: ضع روابط شراء واضحة تعتمد على اسم الماركة ورقم الموديل بالإنجليزية فقط لفتح السلعة بعينها مباشرة، مثل:
  * [🛒 فتح الموديل في أمازون السعودية](https://www.amazon.sa/s?k=الاسم_والموديل_بالإنجليزي)
  * [🟡 فتح الموديل في نون السعودية](https://www.noon.com/saudi-ar/search/?q=الاسم_والموديل_بالإنجليزي)
  * [🔵 فتح الموديل في إكسترا](https://www.extra.com/ar-sa/search/?q=الاسم_والموديل_بالإنجليزي)

3. جدول مقارنة تفصيلي يوضح (الموديل، السعة، التقنية الأبرز، متوسط السعر بالريال، الميزة التنافسية).
4. الختام بنصيحة حاسمة: 'الصفقة الرابحة' (أفضل قيمة مقابل سعر) ولماذا هي الأنسب للشراء اليوم."""

            # تجربة الموديلات بالترتيب لتفادي ضغط السيرفرات (503/429) وضمان التشغيل المستمر
            models_to_try = ['gemini-3.8-flash', 'gemini-3.5-flash', 'gemini-2.5-flash']
            response = None

            for m in models_to_try:
                try:
                    response = client.models.generate_content(
                        model=m,
                        contents=prompt
                    )
                    if response and response.text:
                        break
                except Exception:
                    continue

            if response and response.text:
                st.success("تم تجهيز التقرير الاستشاري وروابط الشراء المباشرة بنجاح!")
                st.markdown(response.text)
            else:
                st.error("خوادم الخدمة تشهد ضغطاً مؤقتاً، يرجى المحاولة بعد بضع ثوانٍ.")
